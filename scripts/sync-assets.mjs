// Copies Vite's staged output into theme/assets and generates snippets/nk-assets.liquid.
//
// Rules (master-plan/04 §4):
// - Shopify's assets/ folder is flat, so any emitted path containing "/" fails the build.
// - Only files this script produced (listed in assets.owned.json) are ever deleted, so merchant
//   or hand-maintained assets survive a build.
// - Liquid can't read the manifest at request time, so the module graph is baked into a snippet.
import { copyFileSync, existsSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const stage = join(root, '.build');
const assetsDir = join(root, 'theme', 'assets');
const ownedFile = join(root, 'assets.owned.json');
const snippetFile = join(root, 'theme', 'snippets', 'nk-assets.liquid');

const manifest = JSON.parse(readFileSync(join(stage, '.vite', 'manifest.json'), 'utf8'));

const emitted = readdirSync(stage).filter((name) => !name.startsWith('.'));
for (const name of emitted) {
  if (statSync(join(stage, name)).isDirectory()) {
    throw new Error(`Build emitted a directory "${name}"; Shopify assets must be flat.`);
  }
  if (!name.startsWith('nk-')) {
    throw new Error(`Build emitted "${name}" without the nk- prefix; owned assets must be identifiable.`);
  }
}

const previous = existsSync(ownedFile) ? JSON.parse(readFileSync(ownedFile, 'utf8')) : [];
for (const name of previous) {
  if (!emitted.includes(name) && existsSync(join(assetsDir, name))) rmSync(join(assetsDir, name));
}
for (const name of emitted) copyFileSync(join(stage, name), join(assetsDir, name));
writeFileSync(ownedFile, JSON.stringify(emitted.sort(), null, 2) + '\n');

// Walk static imports so each entry preloads its whole graph once.
function collect(key, seen = new Set()) {
  const chunk = manifest[key];
  if (!chunk || seen.has(key)) return seen;
  seen.add(key);
  for (const dep of chunk.imports ?? []) collect(dep, seen);
  return seen;
}

const entries = Object.entries(manifest).filter(([, chunk]) => chunk.isEntry);
const branches = entries
  .map(([key, chunk]) => {
    const graph = [...collect(key)];
    const preloads = graph.filter((k) => k !== key).map((k) => manifest[k].file);
    // Motion runtime: fetched in parallel with the entry so pre-hidden text never waits on it.
    if (chunk.name === 'global') {
      const motion = Object.values(manifest).find((c) => c.name === 'gsap' && !c.isEntry);
      if (motion && !preloads.includes(motion.file)) preloads.push(motion.file);
    }
    const css = [...new Set(graph.flatMap((k) => manifest[k].css ?? []))];
    const lines = [
      `  {%- when '${chunk.name}' -%}`,
      ...css.map((file) => `    {{ '${file}' | asset_url | stylesheet_tag }}`),
      // Chunks import each other by bare URL; the preload must match it exactly (no ?v=) or the
      // browser fetches the module twice.
      ...preloads.map((file) => `    <link rel="modulepreload" href="{{ '${file}' | asset_url | split: '?' | first }}">`),
      `    <script src="{{ '${chunk.file}' | asset_url }}" type="module" defer></script>`,
    ];
    return lines.join('\n');
  })
  .join('\n');

const snippet = `{%- doc -%}
  GENERATED by scripts/sync-assets.mjs from the Vite manifest. Do not edit by hand.

  Outputs the stylesheet, module preloads and module script for one built entry.

  @param {string} entry - Entry name: ${entries.map(([, c]) => c.name).join(', ')}

  @example
  {% render 'nk-assets', entry: 'global' %}
{%- enddoc -%}
{%- case entry -%}
${branches}
{%- endcase -%}
`;
writeFileSync(snippetFile, snippet);

console.log(`sync-assets: ${emitted.length} files -> theme/assets; ${entries.length} entries in nk-assets.liquid`);
